import React, { useEffect } from 'react';
import { Link, useParams } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { Printer } from 'lucide-react';
import { rehearsalsApi } from '@/lib/rehearsals';
import { Report } from './ReportPage';

/** Light, paginated version of the report. "Save as PDF" in the print dialog makes the file. */
export function PrintReportPage() {
  const { rehearsalId = '' } = useParams();
  const { data: r } = useQuery({ queryKey: ['rehearsal', rehearsalId], queryFn: () => rehearsalsApi.get(rehearsalId) });

  useEffect(() => {
    document.title = r ? `Pitch report - ${r.title}` : 'Pitch report';
    // The app shell locks body scrolling; this page needs normal document scrolling.
    document.body.style.overflow = 'auto';
    return () => {
      document.body.style.overflow = '';
      document.title = 'AI Pitch Coach';
    };
  }, [r]);

  if (!r) return <p className="p-6 text-sm">Loading...</p>;
  if (r.status !== 'done') return <p className="p-6 text-sm">This report is not ready yet.</p>;

  return (
    <div className="paper min-h-screen">
      <div className="keep-palette no-print sticky top-0 z-10 flex items-center justify-between border-b border-neutral-200 bg-white px-6 py-3">
        <Link to={`/report/${r.id}`} className="text-sm underline">
          ← Back to the report
        </Link>
        <button onClick={() => window.print()} className="flex items-center gap-1.5 rounded-lg border px-3 py-1.5 text-sm" data-testid="print">
          <Printer className="h-4 w-4" /> Print / save as PDF
        </button>
      </div>
      <Report r={r} printMode />
      <p className="mx-auto max-w-4xl px-8 pb-8 text-[10px]">
        Generated by AI Pitch Coach on {new Date().toLocaleString()}. Measurements were computed locally; camera frames never left the device.
      </p>
    </div>
  );
}
